
using System.Text;

namespace EfQueryAnalyzer.Generation;

public static class QuerySourceGenerator
{
    public static async Task<string> GenerateAsync(
        IEnumerable<GeneratedQuery> queries,
        string outputDirectory)
    {
        Directory.CreateDirectory(outputDirectory);

        var filePath = Path.Combine(
            outputDirectory,
            "GeneratedQueries.cs");

        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("using System;");
        builder.AppendLine("using System.Threading.Tasks;");
        builder.AppendLine("using Microsoft.EntityFrameworkCore;");
        builder.AppendLine(
            "using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine();

        builder.AppendLine(
            "namespace EfQueryValidation.Generated;");
        builder.AppendLine();

        builder.AppendLine(
            "public static class GeneratedQueries");
        builder.AppendLine("{");

        builder.AppendLine(
            "    public static async Task ExecuteAsync(");
        builder.AppendLine(
            "        IServiceProvider serviceProvider)");
        builder.AppendLine("    {");

        foreach (var query in queries)
        {
            var rewriter = new QueryContextRewriter(
                query.ContextReference);

            var rewrittenQuery = rewriter.Visit(
                query.Expression);

            if (rewrittenQuery is null)
                continue;

            builder.AppendLine();
            builder.AppendLine(
                $"        // Query: {query.Id}");

            builder.AppendLine("        {");
            builder.AppendLine("            try");
            builder.AppendLine("            {");

            // Resolve the original DbContext interface.
            builder.AppendLine(
                $"                var {query.ContextReference.Name} = " +
                $"serviceProvider.GetRequiredService<" +
                $"{query.ContextReference.TypeName}>();");

            // Declare external parameters.
            foreach (var declaration in query.ParameterDeclarations)
            {
                builder.AppendLine(
                    $"                {declaration}");
            }

            builder.AppendLine();

            // Execute the original query.
            builder.AppendLine(
                $"                var result_{query.Id} = await " +
                $"{rewrittenQuery};");

            builder.AppendLine(
                $"                Console.WriteLine(\"PASS: {query.Id}\");");

            builder.AppendLine("            }");
            builder.AppendLine("            catch (Exception ex)");
            builder.AppendLine("            {");

            builder.AppendLine(
                $"                Console.WriteLine(" +
                $"$\"FAIL: {query.Id} - {{ex.Message}}\");");

            builder.AppendLine("            }");
            builder.AppendLine("        }");
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");

        await File.WriteAllTextAsync(
            filePath,
            builder.ToString(),
            Encoding.UTF8);

        return filePath;
    }
}

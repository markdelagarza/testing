
using System.Text;
using EfQueryAnalyzer.Extraction;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace EfQueryAnalyzer.Generation;

public static class QuerySourceGenerator
{
    public static async Task<string> GenerateAsync(
        ExpressionSyntax query,
        QueryContextReference contextReference,
        IReadOnlyList<string> parameterDeclarations,
        string outputDirectory)
    {
        Directory.CreateDirectory(outputDirectory);

        var filePath = Path.Combine(
            outputDirectory,
            "GeneratedQueries.cs");

        // Remove "this." from the DbContext reference.
        var rewriter = new QueryContextRewriter(
            contextReference);

        var rewrittenQuery = rewriter.Visit(query);

        if (rewrittenQuery is null)
        {
            throw new InvalidOperationException(
                "Unable to rewrite the DbContext reference.");
        }

        var builder = new StringBuilder();

        // File header
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("using System;");
        builder.AppendLine("using System.Threading.Tasks;");
        builder.AppendLine("using Microsoft.EntityFrameworkCore;");
        builder.AppendLine(
            "using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine();

        builder.AppendLine(
            "namespace EfQueryValidation.Generated;");
        builder.AppendLine();

        builder.AppendLine(
            "public static class GeneratedQueries");
        builder.AppendLine("{");

        // Main execution method
        builder.AppendLine(
            "    public static async Task ExecuteAsync(");
        builder.AppendLine(
            "        IServiceProvider serviceProvider)");
        builder.AppendLine("    {");

        // Resolve DbContext through DI.
        builder.AppendLine(
            $"        var {contextReference.Name} = " +
            $"serviceProvider.GetRequiredService<" +
            $"{contextReference.TypeName}>();");

        builder.AppendLine();

        // Generate external parameter declarations.
        foreach (var declaration in parameterDeclarations)
        {
            builder.AppendLine(
                $"        {declaration}");
        }

        if (parameterDeclarations.Count > 0)
            builder.AppendLine();

        // Execute the original EF query.
        builder.AppendLine(
            $"        var result_1 = await {rewrittenQuery};");

        builder.AppendLine("    }");
        builder.AppendLine("}");

        await File.WriteAllTextAsync(
            filePath,
            builder.ToString(),
            Encoding.UTF8);

        return filePath;
    }
}
